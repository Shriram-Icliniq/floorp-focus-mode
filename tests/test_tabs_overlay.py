"""Temporary tabs overlays against the isolated browser, not a live user profile."""
import json,time,sys
from pathlib import Path
from marionette_client import Marionette
m=Marionette(int(sys.argv[1]) if len(sys.argv)>1 else 2878)
checks=[]
def js(s):
 r=m.js(s);return r.get('value',r) if isinstance(r,dict) else r
def check(name,ok):
 assert ok,name
 checks.append(name);print('PASS',name,flush=True)
def wait(n=.16):time.sleep(n)
# The palette integration suite intentionally ends with its preview open.
# Dismiss it before testing real pointer interaction with the tab rail.
js("if(document.getElementById('command-palette-overlay')) window.dispatchEvent(new Event('floorp-command-palette-toggle'));window.FocusCommandLine?.close();")
wait()
m.cmd('WebDriver:PerformActions',{'actions':[{'type':'pointer','id':'mouse','parameters':{'pointerType':'mouse'},'actions':[{'type':'pointerMove','origin':'viewport','x':900,'y':400,'duration':0}]}]})
js("Services.prefs.setBoolPref('sidebar.verticalTabs',false);FocusMode.normal();FocusMode.state.addressPinned=false;FocusMode.state.tabsVisible=false;FocusMode.enable();gURLBar.blur();gBrowser.selectedBrowser.focus();window.__overlayTestTabs=[];")
wait(2.3)
baseline=js("const p=gBrowser.selectedBrowser.getBoundingClientRect();return {top:p.top,width:p.width};")
js("const t=gBrowser.addTrustedTab('about:blank',{skipAnimation:true});window.__overlayTestTabs.push(t);")
wait()
check('opening a tab reveals temporary tabs',js("return FocusMode.state.tabsTemporary && document.documentElement.hasAttribute('focus-tabs-overlay');"))
check('horizontal tabs overlay does not shift or resize page',js(f"const p=gBrowser.selectedBrowser.getBoundingClientRect();return p.top==={baseline['top']} && p.width==={baseline['width']} && getComputedStyle(document.getElementById('TabsToolbar')).position==='absolute';"))
check('tab-only horizontal reveal leaves address bar hidden',js("return !document.documentElement.hasAttribute('focus-address-visible');"))
# Explicitly show both bars to check their combined overlay geometry.
js("FocusMode.reveal('overlay geometry test');")
wait()
check('temporary address bar and horizontal tabs do not overlap',js("return document.getElementById('nav-bar').getBoundingClientRect().top>=document.getElementById('TabsToolbar').getBoundingClientRect().bottom-1;"))
wait(.5)
check('temporary tabs remain during grace period',js("return document.documentElement.hasAttribute('focus-tabs-visible');"))
wait(.7)
js("gBrowser.selectedTab=window.__overlayTestTabs[0];gBrowser.selectedBrowser.focus();")
wait(1.05)
check('another tab action resets the two-second timer',js("return FocusMode.state.lastTabActivity==='TabSelect' && document.documentElement.hasAttribute('focus-tabs-visible');"))
wait(1.15)
check('temporary horizontal tabs disappear after inactivity',js("return !document.documentElement.hasAttribute('focus-tabs-visible') && getComputedStyle(document.getElementById('TabsToolbar')).display==='none';"))
js("gBrowser.pinTab(window.__overlayTestTabs[0]);")
wait()
check('pinning a tab triggers reveal',js("return FocusMode.state.lastTabActivity==='TabPinned' && document.documentElement.hasAttribute('focus-tabs-overlay');"))
js("gBrowser.unpinTab(window.__overlayTestTabs[0]);")
wait()
check('unpinning a tab triggers reveal',js("return FocusMode.state.lastTabActivity==='TabUnpinned';"))
js("const t=gBrowser.addTrustedTab('about:blank',{skipAnimation:true});window.__overlayTestTabs.push(t);gBrowser.moveTabTo(t,{tabIndex:0});")
wait()
check('moving a tab triggers reveal',js("return FocusMode.state.lastTabActivity==='TabMove';"))
js("gBrowser.removeTab(window.__overlayTestTabs.pop(),{animate:false});")
wait()
check('closing a tab triggers reveal',js("return ['TabClose','TabSelect'].includes(FocusMode.state.lastTabActivity) && document.documentElement.hasAttribute('focus-tabs-overlay');"))
js("FocusMode.toggleTabs();")
wait(2.25)
check('permanent horizontal tabs stay in normal layout',js("return FocusMode.state.tabsVisible && !document.documentElement.hasAttribute('focus-tabs-overlay') && getComputedStyle(document.getElementById('TabsToolbar')).position!=='absolute';"))
js("FocusMode.toggleTabs();Services.prefs.setBoolPref('sidebar.verticalTabs',true);")
wait(2.4)
baseline=js("const p=gBrowser.selectedBrowser.getBoundingClientRect();return {top:p.top,left:p.left,width:p.width};")
js("const t=gBrowser.addTrustedTab('about:blank',{skipAnimation:true});window.__overlayTestTabs.push(t);")
wait()
check('tab-only vertical reveal leaves address bar hidden',js("return !document.documentElement.hasAttribute('focus-address-visible');"))
js("FocusMode.reveal('overlay geometry test');")
wait()
metrics=js("const rail=document.querySelector('sidebar-main'),r=rail.getBoundingClientRect(),p=gBrowser.selectedBrowser.getBoundingClientRect(),n=document.getElementById('nav-bar').getBoundingClientRect();return {railWidth:r.width,railTop:r.top,railHeight:r.height,position:getComputedStyle(rail.parentElement).position,pageTop:p.top,pageLeft:p.left,pageWidth:p.width,navbarBottom:n.bottom};")
check('vertical tab rail appears as a visible overlay',metrics['position']=='fixed' and metrics['railWidth']>0 and metrics['railHeight']>0)
check('vertical overlay preserves page width and position',metrics['pageWidth']==baseline['width'] and metrics['pageTop']==baseline['top'] and metrics['pageLeft']==baseline['left'])
check('vertical overlay starts below temporarily visible address bar',metrics['railTop']>=metrics['navbarBottom']-1)
wait(2.2)
check('temporary vertical tabs disappear after inactivity',js("return !document.documentElement.hasAttribute('focus-tabs-overlay') && document.querySelector('sidebar-main').getBoundingClientRect().width===0;"))
js("FocusMode.toggleAddress();FocusMode.revealTabs();")
wait()
check('vertical overlay respects a pinned address bar',js("const rail=document.querySelector('sidebar-main').getBoundingClientRect(),n=document.getElementById('nav-bar').getBoundingClientRect(),p=gBrowser.selectedBrowser.getBoundingClientRect();return rail.top>=n.bottom-1 && p.top>=n.bottom-1;"))
js("FocusMode.toggleTabs();")
wait(2.2)
check('permanent vertical tabs keep normal space reservation',js("return FocusMode.state.tabsVisible && getComputedStyle(document.querySelector('sidebar-main')).position!=='fixed' && !document.documentElement.hasAttribute('focus-tabs-overlay');"))
js("FocusMode.toggleTabs();FocusMode.toggleAddress();FocusMode.revealTabs();")
wait(.15)
# Hover holds an already-visible rail, then starts a fresh grace period on leave.
coords=js("const r=document.querySelector('sidebar-main').getBoundingClientRect();return {x:Math.floor(r.left+r.width/2),y:Math.floor(Math.max(r.top+80,120))};")
def pointer(x,y):m.cmd('WebDriver:PerformActions',{'actions':[{'type':'pointer','id':'mouse','parameters':{'pointerType':'mouse'},'actions':[{'type':'pointerMove','origin':'viewport','x':x,'y':y,'duration':0}]}]})
pointer(coords['x'],coords['y']);wait(2.25)
check('interaction holds an already-visible tabs overlay open',js("return FocusMode.state.tabsHold && document.documentElement.hasAttribute('focus-tabs-overlay');"))
pointer(900,400);wait(2.25)
check('leaving the overlay starts the hide timer',js("return !FocusMode.state.tabsTemporary && !document.documentElement.hasAttribute('focus-tabs-visible');"))
pointer(1,120);wait(.2)
check('hover alone never opens hidden tabs',js("return !document.documentElement.hasAttribute('focus-tabs-visible');"))
pointer(900,400)
js("FocusMode.normal();for(const t of window.__overlayTestTabs)if(t.isConnected)gBrowser.removeTab(t,{animate:false});Services.prefs.setBoolPref('sidebar.verticalTabs',false);")
check('normal mode removes overlay state',js("return !document.documentElement.hasAttribute('focus-tabs-overlay') && !document.documentElement.hasAttribute('focus-tabs-pinned');"))
Path(__file__).with_name('tabs-overlay-results.json').write_text(json.dumps({'passed':len(checks),'checks':checks,'verticalOverlayGeometry':metrics},indent=2))
print('Completed',len(checks),'temporary-tabs checks.')
